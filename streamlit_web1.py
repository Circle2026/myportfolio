def render_analysis():
    st.header("3️⃣ 資料清理、分析與視覺化")

    c1 = section_card("Step 1：資料清理（Data Cleaning）", "🧹")
    c1.markdown(
        """
        - 檢查缺失值（missing values）、重複值（duplicates）、異常值（outliers）。
        - 統一資料格式（日期格式、單位、類別命名一致化）。
        - 常用工具：`pandas`（`isna()`, `drop_duplicates()`, `astype()`）、Excel 篩選/樞紐分析表。
        - **建議在作品集中附上「資料清理前 / 後」的簡短說明**，展示你有意識到資料品質問題。
        """
    )

    c2 = section_card("Step 2：探索性資料分析（EDA）", "🔍")
    c2.markdown(
        """
        1. 先看整體分佈：`describe()`、直方圖、盒鬚圖，了解資料的基本輪廓。
        2. 找關聯與趨勢：相關係數矩陣、時間趨勢圖、群組比較（`groupby`）。
        3. 針對商業問題設計分析角度，例如：
           - 「哪個顧客群貢獻最多營收？」→ RFM / Pareto 分析
           - 「哪個廣告版位轉換率最高？」→ 分組比較 + 顯著性檢定
        """
    )

    c3 = section_card("Step 3：視覺化呈現的原則", "📈")
    c3.markdown(
        """
        - **一張圖只講一件事**：避免把太多指標塞進同一張圖，讓面試官一眼就能看懂重點。
        - **標題直接寫結論**，例如「Q3 高價值顧客貢獻 62% 營收」，而不是只寫「顧客營收分佈圖」。
        - **選對圖表類型**：趨勢用折線圖、佔比用長條圖/圓餅圖（謹慎使用）、分布用盒鬚圖/直方圖、
          相關性用散佈圖/熱力圖。
        - 常用工具：`matplotlib` / `seaborn` / `plotly`（Python）、Tableau Public、Power BI。
        """
    )

    c4 = section_card("Step 4：撰寫分析洞察（Insight & Storytelling）", "📝")
    c4.markdown(
        """
        建議用 **「現況 → 發現 → 建議」** 的架構撰寫每個作品的分析結論：

        - **現況**：這份資料/業務背景是什麼？要解決什麼商業問題？
        - **發現**：透過分析看到了什麼關鍵洞察？（用數字與圖表佐證）
        - **建議**：如果你是決策者，會提出什麼具體的行動建議？

        > 範例：「透過 RFM 分群發現，前 20% 高價值顧客貢獻了 65% 的營收（現況+發現），
        > 建議針對此群體推出會員專屬回購優惠，預期可提升整體回購率 5-8%（建議）。」
        """
    )
    c4.success("✅ 完成一份作品的檢查清單：商業問題明確、資料清理有交代、圖表簡潔有結論、有具體行動建議。")


