    c2.markdown(
        """
        - `load_demo_data()` 函式**只做 `return`**，沒有任何 `to_csv`、`to_sql`、資料庫寫入的程式碼。
        - `st.cache_data` 快取讀取結果，避免每次互動都重新產生/讀取資料，也讓「原始資料」與「展示層」明確分離。
        - `st.multiselect`、`st.checkbox` 這些互動元件只會改變**畫面上顯示的子集合／排序**，
          背後的 `df`（原始資料）在整個 session 中從未被覆寫。
        - `st.dataframe` 預設即為**唯讀表格**（不像 `st.data_editor` 可編輯），適合用在作品集展示情境。
        """
    )
    c2.warning("⚠️ 特別提醒：若使用 `st.data_editor`，該元件允許使用者編輯表格，作品集展示情境請避免使用，改用 `st.dataframe` 或 `st.table`。")


